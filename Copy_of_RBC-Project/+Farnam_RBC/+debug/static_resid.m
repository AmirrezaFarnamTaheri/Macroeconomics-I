function [lhs, rhs] = static_resid(y, x, params)
T = NaN(4, 1);
lhs = NaN(10, 1);
rhs = NaN(10, 1);
T(1) = params(3)*y(2)^params(6);
T(2) = y(1)^params(5);
T(3) = params(10)*y(5)^params(1);
T(4) = y(2)^(1-params(1));
lhs(1) = T(1)/T(2);
rhs(1) = (1-y(9))*y(7);
lhs(2) = 1/T(2);
rhs(2) = params(2)*(1+y(8)*(1-y(10)))/T(2);
lhs(3) = y(7);
rhs(3) = (1-params(1))*y(3)/y(2);
lhs(4) = y(8);
rhs(4) = params(1)*y(3)/y(5);
lhs(5) = y(3);
rhs(5) = T(3)*T(4);
lhs(6) = y(3);
rhs(6) = y(1)+y(4)+y(6);
lhs(7) = y(5);
rhs(7) = y(4)+y(5)*(1-params(4));
lhs(8) = log(y(6));
rhs(8) = log(y(6))*params(7)+x(3);
lhs(9) = log(y(9));
rhs(9) = log(y(9))*params(8)+x(1);
lhs(10) = log(y(10));
rhs(10) = log(y(10))*params(9)+x(2);
end
