function [lhs, rhs] = dynamic_resid(y, x, params, steady_state)
T = NaN(5, 1);
lhs = NaN(10, 1);
rhs = NaN(10, 1);
T(1) = params(3)*y(12)^params(6);
T(2) = y(11)^params(5);
T(3) = y(21)^params(5);
T(4) = params(10)*y(15)^params(1);
T(5) = y(12)^(1-params(1));
lhs(1) = T(1)/T(2);
rhs(1) = (1-y(19))*y(17);
lhs(2) = 1/T(2);
rhs(2) = params(2)*(1+y(18)*(1-y(20)))/T(3);
lhs(3) = y(17);
rhs(3) = (1-params(1))*y(13)/y(12);
lhs(4) = y(18);
rhs(4) = params(1)*y(13)/y(15);
lhs(5) = y(13);
rhs(5) = T(4)*T(5);
lhs(6) = y(13);
rhs(6) = y(11)+y(14)+y(16);
lhs(7) = y(15);
rhs(7) = y(14)+(1-params(4))*y(5);
lhs(8) = log(y(16));
rhs(8) = params(7)*log(y(6))+x(3);
lhs(9) = log(y(19));
rhs(9) = params(8)*log(y(9))+x(1);
lhs(10) = log(y(20));
rhs(10) = params(9)*log(y(10))+x(2);
end
