function [lhs, rhs] = static_resid(y, x, params)
T = NaN(3, 1);
lhs = NaN(12, 1);
rhs = NaN(12, 1);
T(1) = y(3)^params(3);
T(2) = y(5)*T(1);
T(3) = y(4)^(1-params(3));
lhs(1) = y(12);
rhs(1) = 1/y(6);
lhs(2) = params(8)*y(4)^params(9);
rhs(2) = y(12)*y(7)*(1-y(10));
lhs(3) = y(12);
rhs(3) = y(12)*params(1)*(1+y(8)*(1-y(11))-params(2));
lhs(4) = y(7);
rhs(4) = (1-params(3))*y(1)/y(4);
lhs(5) = y(8);
rhs(5) = params(3)*y(1)/y(3);
lhs(6) = y(1);
rhs(6) = T(2)*T(3);
lhs(7) = y(1);
rhs(7) = y(6)+y(2)+y(9);
lhs(8) = y(3);
rhs(8) = y(2)+y(3)*(1-params(2));
lhs(9) = log(y(5));
rhs(9) = log(y(5))*params(4)+x(1);
lhs(10) = log(y(9));
rhs(10) = log(y(9))*params(5)+x(2);
lhs(11) = y(10);
rhs(11) = (1-params(6))*params(10)+y(10)*params(6)+x(3);
lhs(12) = y(11);
rhs(12) = (1-params(7))*params(11)+y(11)*params(7)+x(4);
end
