T(6) = y(2)^(-params(1));
T(7) = (1+y(10))^(-1);
lhs(1) = params(4)/(1-y(2));
rhs(1) = T(1)*y(6);
lhs(2) = T(1);
rhs(2) = T(1)*params(2)*(y(7)+1-params(3));
