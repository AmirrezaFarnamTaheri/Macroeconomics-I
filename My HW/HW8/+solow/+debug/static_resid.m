function [lhs, rhs] = static_resid(y, x, params)
T = NaN(6, 1);
lhs = NaN(10, 1);
rhs = NaN(10, 1);
T(1) = exp(params(7)*((1-y(5))^(1-params(6))-1)/(1-params(6)));
T(2) = (1-y(5))^(-params(6));
T(3) = y(3)^params(3);
T(4) = y(5)^(-params(3));
T(5) = params(3)*exp(y(7))*y(3)^(params(3)-1);
T(6) = y(5)^(1-params(3));
lhs(1) = y(10);
rhs(1) = T(1);
lhs(2) = 1;
rhs(2) = params(1)*(1+y(8)-params(2));
lhs(3) = y(9);
rhs(3) = y(8)-params(2);
lhs(4) = y(6);
rhs(4) = params(7)*y(2)*T(2);
lhs(5) = y(6);
rhs(5) = exp(y(7))*(1-params(3))*T(3)*T(4);
lhs(6) = y(8);
rhs(6) = T(5)*T(6);
lhs(7) = y(2)+y(4);
rhs(7) = y(1);
lhs(8) = y(1);
rhs(8) = T(6)*exp(y(7))*T(3);
lhs(9) = y(3);
rhs(9) = y(4)+y(3)*(1-params(2));
lhs(10) = y(7);
rhs(10) = y(7)*params(4)+x(1);
end
