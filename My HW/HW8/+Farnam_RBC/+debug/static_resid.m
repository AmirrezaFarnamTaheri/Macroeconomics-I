function [lhs, rhs] = static_resid(y, x, params)
T = NaN(8, 1);
lhs = NaN(8, 1);
rhs = NaN(8, 1);
T(1) = (1-y(4))^(-params(6));
T(2) = exp((params(7)*T(1)-1)/(1-params(6)));
T(3) = (y(6)*T(2))^(1-params(5));
T(4) = y(3)^params(3);
T(5) = y(4)^(-params(3));
T(6) = y(3)^(params(3)-1);
T(7) = params(3)*y(5)*T(6);
T(8) = y(4)^(1-params(3));
lhs(1) = T(3);
rhs(1) = T(3)*params(1)*(y(8)+1-params(2));
lhs(2) = y(7);
rhs(2) = T(1)*y(6)*params(7);
lhs(3) = y(7);
rhs(3) = (1-params(3))*y(5)*T(4)*T(5);
lhs(4) = y(8);
rhs(4) = T(7)*T(8);
lhs(5) = y(1);
rhs(5) = T(8)*y(5)*T(4);
lhs(6) = y(1);
rhs(6) = y(6)+y(2);
lhs(7) = y(3);
rhs(7) = y(2)+(1-params(2))*y(3);
lhs(8) = log(y(5));
rhs(8) = log(y(5))*params(4)+x(1);
end
